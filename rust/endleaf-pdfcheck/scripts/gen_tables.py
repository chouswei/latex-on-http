"""Generate src/tables.rs from the pinned pdfminer.six data (MIT).

Usage: python scripts/gen_tables.py   (run with the venv that has pdfminer.six 20260107)
The tables are the Adobe Glyph List, the four latin encodings, the base-14 AFM
metrics (as pdfminer ships them). The CJK CMaps and CID -> Unicode maps are
scripts/gen_cmaps.py (src/cmapdata/).
"""
import os

from pdfminer.encodingdb import EncodingDB
from pdfminer.fontmetrics import FONT_METRICS
from pdfminer.glyphlist import glyphname2unicode

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, "..", "src")


def rs(s):
    out = '"'
    for ch in s:
        o = ord(ch)
        if ch == '"' or ch == "\\":
            out += "\\" + ch
        elif 32 <= o < 127:
            out += ch
        else:
            out += "\\u{%x}" % o
    return out + '"'


lines = ["// @generated by scripts/gen_tables.py from pdfminer.six data. Do not edit.", ""]
lines.append("pub static GLYPHLIST: &[(&str, &str)] = &[")
for name in sorted(glyphname2unicode):
    lines.append(f"    ({rs(name)}, {rs(glyphname2unicode[name])}),")
lines.append("];")
for key, var in (
    ("StandardEncoding", "STD"),
    ("MacRomanEncoding", "MAC"),
    ("WinAnsiEncoding", "WIN"),
    ("PDFDocEncoding", "PDFDOC"),
):
    table = EncodingDB.encodings[key]
    lines.append(f"pub static ENC_{var}: &[(u8, &str)] = &[")
    for code in sorted(table):
        lines.append(f"    ({code}, {rs(table[code])}),")
    lines.append("];")
lines.append("/// (basefont, FontName, Descent, Ascent, widths by unicode char)")
lines.append("#[allow(clippy::type_complexity)] // generated table: (basefont, name, descent, ascent, widths)")
lines.append("pub static BASE14: &[(&str, &str, f64, f64, &[(&str, f64)])] = &[")
for base in sorted(FONT_METRICS):
    desc, widths = FONT_METRICS[base]
    ws = ", ".join(f"({rs(k)}, {float(v)!r})" for k, v in sorted(widths.items()))
    lines.append(
        f"    ({rs(base)}, {rs(str(desc.get('FontName', 'unknown')))}, {float(desc.get('Descent', 0))!r}, "
        f"{float(desc.get('Ascent', 0))!r}, &[{ws}]),"
    )
lines.append("];")
with open(os.path.join(src, "tables.rs"), "w", encoding="utf-8") as fh:
    fh.write("\n".join(lines) + "\n")

print("tables.rs written")
